type Ctx = { lang: Lang; t: (k: StringKey) => string; setLang: (l: Lang) => void };
const I18nContext = createContext<Ctx>({ lang: "it", t: (k) => it[k], setLang: () => {} });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("it");
  // The formatters' language is set before the state, so the re-render already formats in the new language.
  useEffect(() => {
    storage.getItem<string>("eld.lang", "it").then((v) => {
      const next = v && LANGS.some((l) => l.code === v) ? (v as Lang) : "it";
      setFormatterLanguage(next);
      setLangState(next);
    });
  }, []);
  const setLang = useCallback((l: Lang) => {
    setFormatterLanguage(l);
    setLangState(l);
    storage.setItem("eld.lang", l);
  }, []);
  const value = useMemo<Ctx>(() => ({ lang, setLang, t: (k) => dict[lang][k] ?? en[k] ?? k }), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

/** Interpolates `{name}` placeholders. */
export function fmt(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

/** Translate a dynamic key (e.g. `missionName_${key}`) with a fallback when the key is not in the dictionary. */
export function tDyn(t: (k: StringKey) => string, key: string, fallback: string): string {
  const v = t(key as StringKey);
  return v === key ? fallback : v;
}

/** Human unlock line for a locked building / unit gate: "Richiede: Insediamento liv. 3 · ricerca «Tiro con l'Arco» · Caserma". */
export function unlockLine(t: (k: StringKey) => string, u: { min_settlement_level: number; required_research_key: string | null; required_research_name?: string | null }, extra?: string | null): string {
  const parts = [fmt(t("unlockLevel"), { level: u.min_settlement_level })];
  if (u.required_research_key) parts.push(fmt(t("unlockResearch"), { name: u.required_research_name ?? u.required_research_key }));
  if (extra) parts.push(extra);
  return `${t("unlockRequires")}: ${parts.join(" · ")}`;
}


